import asyncio, sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from e2e_lib import *
from playwright.async_api import async_playwright
SH=__import__('os').environ.get('SHOTS','/tmp/')
async def main():
    async with async_playwright() as p:
        b, ctx, pg = await new(p)
        await student_login(pg, 'DEMO26', 1, '1234')
        await pg.screenshot(path=SH+'home.png')
        # 잠긴 장 확인
        locked = await pg.locator('.side-tab[aria-disabled=true]').count()
        print('locked tabs', locked)
        await pg.click('.side-tab:has-text("기상자료 탐험실")')
        await pg.wait_for_timeout(1200)
        await pg.screenshot(path=SH+'weather0.png')
        await pg.fill('.page.right input[placeholder^="예: 서울"]', '서울')
        await pg.select_option('.page.right select', '2021')
        await pg.wait_for_timeout(900)
        await pg.click('text=표 만들기로 넘기기')
        await pg.wait_for_timeout(1300)
        vals=[12, 25, 6, 30, 18]
        for i,v in enumerate(vals):
            await pg.fill(f'input[aria-label="{i+1}번째 폭염일수"]', str(v))
        await pg.wait_for_timeout(900)
        await pg.screenshot(path=SH+'weather1.png')
        await pg.click('text=표 확인하기')
        await pg.wait_for_timeout(1600)
        await pg.screenshot(path=SH+'weather2.png')
        # 그래프 단계
        await pg.evaluate("document.querySelectorAll('.step').forEach(d=>d.open=true)")
        await pg.fill('.step input[placeholder^="예: ○○"]', '서울의 연도별 폭염일수')
        await pg.fill('input[placeholder="예: 연도"]', '연도')
        await pg.fill('input[placeholder="예: 폭염일수"]', '폭염일수')
        sels = pg.locator('.step select')
        await sels.nth(0).select_option('년'); await sels.nth(1).select_option('일')
        await pg.click('.step .chip-btn:text-is("2")')
        await pg.wait_for_timeout(500)
        coords = await graph_coords(pg, [(i,v) for i,v in enumerate(vals)])
        for x,y in coords:
            await pg.mouse.move(x,y); await pg.mouse.down(); await pg.mouse.move(x+1,y); await pg.mouse.up()
            await pg.wait_for_timeout(120)
        await pg.click('.tool-btn:has-text("선 잇기")')
        for x,y in coords:
            await pg.mouse.click(x,y); await pg.wait_for_timeout(100)
        await pg.screenshot(path=SH+'weather3.png')
        d = await pg.evaluate("JSON.stringify({p: window.__editor.d.points, s: window.__editor.d.segments})")
        print('drawn', d)
        ip = pg.locator('.step select')
        await ip.nth(2).select_option('2024년'); await ip.nth(3).select_option('2023년'); await ip.nth(4).select_option('2023년~2024년')
        await pg.fill('.step textarea', '2024년에 폭염일수가 가장 많았고 2023년에 가장 적었어요.')
        await pg.wait_for_timeout(300)
        await pg.click('.step button.btn:text-is("확인하기")')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path=SH+'weather4.png')
        await pg.click('button:has-text("작품 제출하기")')
        await pg.wait_for_timeout(400)
        await pg.click('.modal .btn:has-text("제출하기")')
        await pg.wait_for_timeout(1200)
        await pg.screenshot(path=SH+'weather5.png')
        await pg.click('.modal .btn')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path=SH+'topics0.png')
        print('errors:', pg.errs)
        await b.close()
asyncio.run(main())
